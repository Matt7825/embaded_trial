#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>
int main()
{
	int x, y; 
	printf("Vvedite chislo x \n");
	scanf("%d", & x);
	printf("Vvedite chislo y \n");
	scanf("%d", &y);
	int result1 = x + y;
	int result2 = x - y;
	int result3 = x * y;
	float x_f, y_f;
	scanf("%f", &x_f);
	scanf("%f", &y_f);
	float result4 = x_f / y_f;
	printf("x + y = %d \n", result1);
	printf("x - y = %d \n", result2);
	printf("x * y = %d \n", result3);
	printf("x / y = %f \n", result4);
	return 0;
}

